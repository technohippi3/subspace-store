const fixture = JSON.parse(readFileSync(new URL("journal-envelope-vectors.json", import.meta.url), "utf8")) as {
  store: string; records: { name: string; payload: string; embeddedHash: string; recordDigest: string }[] };
function vector(name: string) { const value = fixture.records.find(value => value.name === name); assert(value); return value; }
const bytes = (text: string) => Buffer.from(text);
const digest = (value: string | Uint8Array) => createHash("sha256").update(value).digest("hex");
const legacy = vector("legacy-compact"), floor = vector("floor-first");
const floorChanges = JSON.parse(floor.payload.slice(6)).changes as Change[];
function legacyPayload(seq: number, previous: string | null, changes: readonly Change[]): Buffer {
  const hash = digest(JSON.stringify([1, fixture.store, seq, previous, changes]));
  return bytes(JSON.stringify({ version: 1, store: fixture.store, seq, previous, changes, hash }));
}
function sizedLegacy(seq: number, previous: string | null, size: number): Buffer {
  const changes: Change[] = [{ kind: "data", key: "alpha", value: "" }];
  const empty = legacyPayload(seq, previous, changes).length;
  changes[0] = { kind: "data", key: "alpha", value: "x".repeat(size - empty) };
  const payload = legacyPayload(seq, previous, changes); assert.equal(payload.length, size); return payload;
}

test("canonical JSON matches literal numeric, UTF-16 ordering and escaping vectors", () => {
  // Numeric samples from RFC 8785 Appendix B, not generated by this codec.
  for (const [bits, expected] of [
    ["8000000000000000", "0"], ["0000000000000001", "5e-324"],
    ["7fefffffffffffff", "1.7976931348623157e+308"], ["44b52d02c7e14af6", "1e+23"],
    ["444b1ae4d6e2ef4f", "999999999999999900000"], ["444b1ae4d6e2ef50", "1e+21"],
    ["3eb0c6f7a0b5ed8d", "0.000001"], ["43143ff3c1cb0959", "1424953923781206.2"],
  ]) assert.equal(canonicalJson(Buffer.from(bits!, "hex").readDoubleBE()), expected);
  assert.equal(canonicalJson({ "2": "two", "10": "ten" }), '{"10":"ten","2":"two"}');
  assert.equal(canonicalJson({ "\ue000": "bmp", "😀": "astral" }), '{"😀":"astral","\ue000":"bmp"}');
  assert.equal(canonicalJson({ z: [3, 2, 1], a: "\b\t\n\f\r\u000f\\\"/" }), '{"a":"\\b\\t\\n\\f\\r\\u000f\\\\\\\"/","z":[3,2,1]}');
  assert.equal(canonicalJson({ ["e\u0301"]: "é", é: "e\u0301" }), '{"e\u0301":"é","é":"e\u0301"}');
});

test("canonical JSON rejects non-JSON data, bad Unicode and cycles without invoking hooks", () => {
  const cycle: unknown[] = []; cycle.push(cycle);
  let invoked = false; const accessor = Object.defineProperty({}, "x", { enumerable: true, get() { invoked = true; return 1; } });
  const hidden = Object.defineProperty([], "toJSON", { value() { invoked = true; return []; } });
  for (const value of [NaN, Infinity, -Infinity, undefined, 1n, new Date(), new Array(1), cycle, hidden,
    { toJSON() { invoked = true; return 1; } }, accessor, "\ud800", "\udfff", { ["\ud800"]: 1 }])
    assert.throws(() => canonicalJson(value));
  assert.equal(invoked, false);
  const deep = "[".repeat(20000) + "0" + "]".repeat(20000);
  assert.equal(canonicalJson(JSON.parse(deep)), deep);
});

test("v2 rejects all I-JSON noncharacters while legacy payloads retain their original behavior", () => {
  const noncharacters = [...Array.from({ length: 32 }, (_, i) => 0xfdd0 + i),
    ...Array.from({ length: 17 }, (_, plane) => [plane * 65536 + 65534, plane * 65536 + 65535]).flat()];
  assert.equal(new Set(noncharacters).size, 66);
  for (const codepoint of noncharacters) {
    const text = String.fromCodePoint(codepoint);
    assert.throws(() => canonicalJson(text), /Unicode/);
    assert.throws(() => canonicalJson({ [text]: 1 }), /Unicode/);
    const old = legacyPayload(1, null, [{ kind: "data", key: "alpha", value: text }]);
    assert.equal(readJournalPayload(old).payload, old.toString());
    // Independent known-order JCS serialization with a correct embedded hash:
    // rejection must be character admission, not a bad checksum or unknown frame.
    const changes = '[{"key":"alpha","kind":"data","value":' + JSON.stringify(text) + '}]';
    const preimage = '[2,' + JSON.stringify(fixture.store) + ',1,null,' + changes + ']';
    const raw = 'SSSJ2 {"changes":' + changes + ',"hash":"' + digest(preimage) +
      '","previous":null,"seq":1,"store":' + JSON.stringify(fixture.store) + ',"version":2}';
    assert.throws(() => readJournalPayload(bytes(raw)), /Unicode/);
  }
  for (const codepoint of [0xfdcf, 0xfdf0, 0xfffd, 0x1fffd, 0x10fffd])
    assert.equal(canonicalJson(String.fromCodePoint(codepoint)), JSON.stringify(String.fromCodePoint(codepoint)));
  const old = legacyPayload(1, null, [{ kind: "data", key: "alpha", value: String.fromCodePoint(0xfdd0) }]);
  const escaped = old.toString().replace(String.fromCodePoint(0xfdd0), "\\ufdd0");
  assert.equal(readJournalPayload(bytes(escaped)).payload, escaped);
});

test("independent envelope fixtures retain exact payload and both distinct digests", () => {
  for (const expected of fixture.records) {
    const record = readJournalPayload(bytes(expected.payload));
    assert.equal(record.validation, "envelope-only"); assert.equal(record.payload, expected.payload);
    assert.deepEqual(record.bytes, Uint8Array.from(bytes(expected.payload)));
    assert.equal(record.entry.hash, expected.embeddedHash); assert.equal(record.recordDigest, expected.recordDigest);
    if (record.entry.version === 2) {
      assert.equal(encodeJournalEnvelope(record.entry.store, record.entry.seq, record.entry.previous, record.entry.changes).payload, expected.payload);
      assert.throws(() => legacyDecode(expected.payload));
    } else assert.deepEqual(record.entry, legacyDecode(expected.payload));
  }
  assert.equal(vector("legacy-pretty").embeddedHash, legacy.embeddedHash);
  assert.notEqual(vector("legacy-pretty").recordDigest, legacy.recordDigest);
  assert.equal(vector("legacy-duplicate-exponent").embeddedHash, legacy.embeddedHash);
});

test("payload views own input/output bytes and deeply freeze their parsed data", () => {
  const input = bytes(legacy.payload), record = readJournalPayload(input); input.fill(0);
  const output = record.bytes; output.fill(0);
  assert.equal(record.payload, legacy.payload); assert.equal(digest(record.bytes), legacy.recordDigest);
  assert.throws(() => { (record as unknown as { payload: string }).payload = "changed"; }, TypeError);
  assert.throws(() => { (record.entry.changes[0]!.value as { b: number }).b = 9; }, TypeError);
  assert.throws(() => { (record.entry.changes as Change[]).push({ kind: "data", key: "other", value: 0 }); }, TypeError);
});

test("file LF handling preserves legacy whitespace and admits exactly one new physical LF", () => {
  const text = vector("legacy-pretty").payload;
  assert.equal(readJournalFile(bytes(text)).payload, text);
  assert.equal(readJournalFile(bytes(text + "\n")).payload, text);
  assert.equal(readJournalFile(bytes(text + "\n\n")).payload, text + "\n");
  assert.equal(readJournalPayload(bytes(text + "\n")).payload, text + "\n");
  const record = readJournalPayload(bytes(floor.payload));
  assert.equal(Buffer.from(journalFileBytes(record)).toString(), floor.payload + "\n");
  assert.equal(readJournalFile(journalFileBytes(record)).payload, floor.payload);
  assert.throws(() => readJournalFile(record.bytes));
  assert.throws(() => readJournalFile(bytes(floor.payload + "\n\n")));
  assert.throws(() => readJournalPayload(bytes(floor.payload + "\n")));
  assert.throws(() => journalFileBytes(readJournalPayload(bytes(legacy.payload))));
  const forged = { ...record, bytes: bytes(legacy.payload) } as EnvelopeRecord;
  assert.throws(() => journalFileBytes(forged));
});

